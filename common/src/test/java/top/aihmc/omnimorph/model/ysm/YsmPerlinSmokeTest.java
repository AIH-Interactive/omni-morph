package top.aihmc.omnimorph.model.ysm;

import net.minecraft.SharedConstants;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.entity.decoration.ArmorStand;
import sun.misc.Unsafe;
import top.aihmc.omnimorph.avatar.Avatar;
import top.aihmc.omnimorph.molang.MolangEngine;
import top.aihmc.omnimorph.molang.runtime.ExpressionEvaluator;
import top.aihmc.omnimorph.molang.runtime.Function;
import top.aihmc.omnimorph.molang.runtime.binding.MolangBindings;

import java.util.Locale;
import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;

public final class YsmPerlinSmokeTest {
    private static final MolangEngine ENGINE = MolangEngine.fromCustomBinding(new MolangBindings());

    // Frozen from LWJGL 3.4.1 STBPerlin, not generated by the Java implementation.
    private static final float[][] NATIVE_VECTORS = {
            {0, 0.25f, 0f, 0f, 0.07763672f},
            {0, 0.25f, 0.5f, 0f, -0.46118164f},
            {0, 0.25f, 0.5f, 0.75f, -0.06729746f},
            {0, -0.25f, -1.5f, 2.75f, 0.056660652f},
            {0, 255.75f, 256.5f, -256.25f, -0.24107885f},
            {1, 0.25f, 0f, 0f, -0.2241211f},
            {1, 0.25f, 0.5f, 0f, -0.5991211f},
            {1, 0.25f, 0.5f, 0.75f, -0.5062423f},
            {1, -0.25f, -1.5f, 2.75f, -0.1879816f},
            {1, 255.75f, 256.5f, -256.25f, -0.23572111f},
            {42, 0.25f, 0f, 0f, 0.14648438f},
            {42, 0.25f, 0.5f, 0f, -0.051757812f},
            {42, 0.25f, 0.5f, 0.75f, 0.09108448f},
            {42, -0.25f, -1.5f, 2.75f, -0.5964422f},
            {42, 255.75f, 256.5f, -256.25f, 0.028102875f},
            {255, 0.25f, 0f, 0f, 0.2241211f},
            {255, 0.25f, 0.5f, 0f, -0.2758789f},
            {255, 0.25f, 0.5f, 0.75f, -0.09831524f},
            {255, -0.25f, -1.5f, 2.75f, 0.106194496f},
            {255, 255.75f, 256.5f, -256.25f, -0.22998714f}
    };

    public static void main(String[] args) throws Exception {
        Path environment = Files.createTempDirectory("figura-perlin-environment-").toAbsolutePath().normalize();
        String previous = System.getProperty("figura.test.directory");
        System.setProperty("figura.test.directory", environment.toString());
        try {
            SharedConstants.tryDetectVersion();
            Bootstrap.bootStrap();
            runTests();
        } finally {
            if (previous == null) {
                System.clearProperty("figura.test.directory");
            } else {
                System.setProperty("figura.test.directory", previous);
            }
            try (var files = Files.walk(environment)) {
                for (Path path : files.sorted(Comparator.reverseOrder()).toList()) {
                    if (!path.toAbsolutePath().normalize().startsWith(environment)) {
                        throw new IllegalStateException("Unexpected fixture cleanup path");
                    }
                    Files.delete(path);
                }
            }
        }
    }

    private static void runTests() throws Exception {
        Avatar.MolangContext context = new Avatar.MolangContext(null);
        Field unsafeField = Unsafe.class.getDeclaredField("theUnsafe");
        unsafeField.setAccessible(true);
        // Only the native entity type is needed by this pure numeric binding.
        context.entity = (ArmorStand) ((Unsafe) unsafeField.get(null)).allocateInstance(ArmorStand.class);
        for (float[] vector : NATIVE_VECTORS) {
            int seed = (int) vector[0];
            float x = vector[1];
            float y = vector[2];
            float z = vector[3];
            float expected = vector[4];
            equal(expected, YsmPerlinNoise.sample(seed, x, y, z), "native fixed vector");
            String expression = String.format(Locale.ROOT, "ysm.perlin_noise(%d,%s,%s,%s);", seed, x, y, z);
            equal(expected, evaluate(context, expression), "actual parser/binding fixed vector");
            equal(expected, YsmPerlinNoise.sample(seed + 256, x, y, z), "only low seed byte used");
            equal(expected, YsmPerlinNoise.sample(seed - 256, x, y, z), "negative seed wraps by byte");
            equal(expected, YsmPerlinNoise.sample(seed, x + 256f, y - 256f, z + 256f), "coordinate period");
        }
        equal(0.07763672f, evaluate(context, "ysm.perlin_noise(0,0.25);"), "one-dimensional defaults");
        equal(-0.46118164f, evaluate(context, "ysm.perlin_noise(0,0.25,0.5);"), "two-dimensional defaults");
        equal(-0.2241211f, evaluate(context, "ysm.perlin_noise(1.9,0.25,0,0,99);"),
                "integer seed conversion and ignored excess arguments");
        equal(0.2241211f, YsmPerlinNoise.sample(Integer.MAX_VALUE, 0.25f, 0f, 0f), "maximum seed");
        equal(0.07763672f, YsmPerlinNoise.sample(Integer.MIN_VALUE, 0.25f, 0f, 0f), "minimum seed");
        equal(0f, YsmPerlinNoise.sample(42, -2f, 5f, 9f), "integer lattice");
        equal(0f, YsmPerlinNoise.sample(0, Float.NaN, 0f, 0f), "nonfinite input safety");
        equal(0f, YsmPerlinNoise.sample(0, 0f, Float.POSITIVE_INFINITY, 0f), "infinite input safety");
        equal(0f, YsmPerlinNoise.sample(0, Float.MAX_VALUE, 0f, 0f), "coordinate int conversion boundary");
        Function function = (Function) new MolangBindings.YsmBinding().getProperty("perlin_noise");
        require(!function.validateArgumentSize(1) && function.validateArgumentSize(2)
                && function.validateArgumentSize(3) && function.validateArgumentSize(4)
                && function.validateArgumentSize(5), "reference signature");
        System.out.println("M4 pure Java Perlin: native vectors, actual binding, defaults, seed/coordinate wrapping and safety passed.");
    }

    private static float evaluate(Avatar.MolangContext context, String source) throws Exception {
        return ExpressionEvaluator.evaluator(context).evalAsFloat(ENGINE.parse(source).getFirst());
    }

    private static void equal(float expected, float actual, String message) {
        require(Float.isFinite(actual) && Math.abs(expected - actual) <= 0.000002f,
                message + ": " + expected + " / " + actual);
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
